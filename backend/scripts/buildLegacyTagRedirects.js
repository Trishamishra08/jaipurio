/**
 * Builds the nginx 301 map for OLD product-tag URLs of the previous site.
 *
 * The old shop had ~3,600 /product-tags/<tag> pages (also under /fr/, /de/ ... prefixes).
 * The new site has no tag pages, so they answered 410. Where an old tag clearly names a
 * product category that exists today ("work-bag" -> Bags), send the visitor and Google
 * there with a 301 instead. Everything else stays 410 (gone), never a vague redirect.
 *
 *   node scripts/buildLegacyTagRedirects.js                 # writes ../frontend/legacy-tag-redirects.conf
 *   node scripts/buildLegacyTagRedirects.js --categories https://jaipurio.in/sitemap-categories.xml --old "../old db"
 *
 * Matching rule (strict on purpose, a wrong redirect is worse than a 410):
 *   every word of the CATEGORY must appear in the tag, and the category with the most
 *   words wins. Two equally specific categories => no redirect.
 * Re-run it when categories change; commit the generated file.
 */
const fs = require('fs');
const path = require('path');

const argv = process.argv.slice(2);
const opt = (name, fallback) => {
  const i = argv.indexOf(`--${name}`);
  return i >= 0 && argv[i + 1] ? argv[i + 1] : fallback;
};
const CATEGORIES_URL = opt('categories', 'https://jaipurio.in/sitemap-categories.xml');
const OLD_DIR = path.resolve(opt('old', path.join(__dirname, '..', '..', 'old db')));
const OUT = path.resolve(opt('out', path.join(__dirname, '..', '..', 'frontend', 'legacy-tag-redirects.conf')));

// Categories too broad to be a good home for a specific tag.
const TOO_BROAD = new Set(['men', 'women', 'kids', 'all', 'sale', 'new', 'offers', 'gifts', 'gift', 'accessories', 'clothing']);
const SAFE = /^[a-z0-9][a-z0-9-]*$/;

const stem = (w) => (w.length > 3 && w.endsWith('s') && !w.endsWith('ss') ? w.slice(0, -1) : w);
const words = (s) =>
  String(s || '')
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter(Boolean)
    .map(stem);

/** Streams the (huge) legacy export and returns the set of old product-tag slugs. */
function readOldTags(file) {
  const fd = fs.openSync(file, 'r');
  const size = fs.fstatSync(fd).size;
  const CHUNK = 32 * 1024 * 1024;
  const OVERLAP = 3000;
  const buf = Buffer.alloc(CHUNK);
  const tags = new Set();
  const re = /"key":"([a-z0-9\-_%]+)","reference_id":(\d+),"reference_type":"Botble\\\\+Ecommerce\\\\+Models\\\\+ProductTag"/g;
  let pos = 0;
  let carry = '';
  while (pos < size) {
    const n = fs.readSync(fd, buf, 0, CHUNK, pos);
    pos += n;
    const text = carry + buf.toString('utf8', 0, n);
    re.lastIndex = 0;
    let m;
    while ((m = re.exec(text))) tags.add(m[1]);
    carry = text.slice(-OVERLAP);
  }
  fs.closeSync(fd);
  return tags;
}

/** Best category for one tag, or null. */
function matchCategory(tagSlug, cats) {
  const tw = new Set(words(tagSlug));
  let best = [];
  let bestLen = 0;
  for (const c of cats) {
    if (c.w.length === 0 || !c.w.every((w) => tw.has(w))) continue;
    if (c.w.length > bestLen) {
      best = [c];
      bestLen = c.w.length;
    } else if (c.w.length === bestLen) {
      best.push(c);
    }
  }
  return best.length === 1 ? best[0] : null;
}

(async () => {
  const xml = await (await fetch(CATEGORIES_URL)).text();
  const cats = [...xml.matchAll(/<loc>[^<]*\/product-categories\/([^<]+)<\/loc>/g)]
    .map((m) => m[1])
    .filter((s) => SAFE.test(s) && !TOO_BROAD.has(s))
    .map((slug) => ({ slug, w: words(slug) }));
  if (!cats.length) throw new Error(`No categories read from ${CATEGORIES_URL}`);

  const tags = readOldTags(path.join(OLD_DIR, 'legacy-export.json'));
  // Tags seen in Search Console's 404 report that may not be in the export.
  const extra = opt('extra', '');
  if (extra) fs.readFileSync(extra, 'utf8').split(/\r?\n/).filter(Boolean).forEach((t) => tags.add(t));

  const map = new Map();
  let unsafe = 0;
  for (const t of [...tags].sort()) {
    if (!SAFE.test(t)) {
      unsafe += 1;
      continue;
    }
    const c = matchCategory(t, cats);
    if (c) map.set(t, c.slug);
  }

  const lines = [
    '# GENERATED by backend/scripts/buildLegacyTagRedirects.js — do not edit by hand.',
    '# Old /product-tags/<tag> pages -> the live category the tag names (301). Other tags stay 410.',
    `# ${map.size} of ${tags.size} old tags mapped.`,
    '',
    '# Tag slug from /product-tags/<tag> or /<lang>/product-tags/<tag> ("" for any other URL).',
    'map $uri $legacy_tag_slug {',
    '    default "";',
    '    ~*^(?:/(?:fr|de|es|pt|it|ru|nl|pl|tr|ja|zh|ar))?/product-tags/(?<legacy_tag>[a-z0-9-]+)/?$ $legacy_tag;',
    '}',
    '',
    'map $legacy_tag_slug $legacy_tag_target {',
    '    default "";',
    ...[...map].map(([tag, cat]) => `    "${tag}" "/product-categories/${cat}";`),
    '}',
    '',
  ];
  fs.writeFileSync(OUT, lines.join('\n'));
  console.log({ oldTags: tags.size, mapped: map.size, left410: tags.size - map.size - unsafe, skippedUnsafe: unsafe });
  const byCat = {};
  map.forEach((c) => { byCat[c] = (byCat[c] || 0) + 1; });
  console.log('tags per category:', byCat);
  console.log('sample:', [...map].slice(0, 12).map(([t, c]) => `${t} -> ${c}`));
  console.log(`Wrote ${OUT}`);
})().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
